"""counsel declares its direct dependencies on three surfaces; they must agree.

* `counsel/pyproject.toml [project.dependencies]` -- package metadata that tooling
  (and humans) read;
* `counsel/requirements.txt` -- the input `uv pip compile` turns into the lock;
* `counsel/requirements.lock` -- the hashed surface Docker and CI actually install.

Divergence is silent: `anyio` was imported by `app/counsel_mcp.py` and pinned in
`requirements.txt`, yet missing from the metadata, so installing from the declared
dependencies produced a broken environment. The lock is intentionally frozen (it is
not regenerated on every change, which would bump transitive pins), so this pins the
declared pins instead.
"""
from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COUNSEL = ROOT / "counsel"
PYPROJECT = COUNSEL / "pyproject.toml"
REQUIREMENTS = COUNSEL / "requirements.txt"
LOCK = COUNSEL / "requirements.lock"
TEST_README = ROOT / "tests" / "README.md"

_PIN = re.compile(r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)==(?P<version>[^\s;\\]+)")


def _normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _pins(text: str) -> dict[str, str]:
    pins: dict[str, str] = {}
    for line in text.splitlines():
        match = _PIN.match(line.strip())
        if match:
            key = _normalize(match.group("name"))
            assert key not in pins, f"duplicate pin for {key}"
            pins[key] = match.group("version")
    return pins


def _declared() -> dict[str, str]:
    return _pins("\n".join(tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))["project"]["dependencies"]))


def test_pyproject_and_requirements_declare_the_same_pins():
    declared, listed = _declared(), _pins(REQUIREMENTS.read_text(encoding="utf-8"))
    assert declared == listed, {
        "pyproject_only": sorted(declared.keys() - listed.keys()),
        "requirements_only": sorted(listed.keys() - declared.keys()),
        "version_mismatch": {
            key: (declared[key], listed[key]) for key in declared.keys() & listed.keys() if declared[key] != listed[key]
        },
    }


def test_every_declared_dependency_is_pinned_in_the_lock():
    declared, locked = _declared(), _pins(LOCK.read_text(encoding="utf-8"))
    missing = {
        name: (version, locked.get(name)) for name, version in declared.items() if locked.get(name) != version
    }
    assert not missing, missing


def test_lock_was_compiled_for_the_supported_python():
    requires_python = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))["project"]["requires-python"]
    minor = re.search(r">=\s*(\d+\.\d+)", requires_python)
    assert minor, requires_python
    command = TEST_README.read_text(encoding="utf-8")
    assert f"--python {minor.group(1)}" in command, (
        f"tests/README.md must document compiling the lock for {minor.group(1)}"
    )
    assert LOCK.read_text(encoding="utf-8").startswith("# This file was autogenerated by uv"), (
        "the lock must stay generated, never hand-edited"
    )


def test_declared_pins_cover_every_third_party_import():
    """Every third-party module import must be one of the declared pins.

    `counsel/app/**/tools/` adds its own directory to `sys.path`, so sibling modules
    are imported flat (`from chart_id import chart_id`); a name is local when it is a
    file stem anywhere under `counsel/app`, which leaves only real distributions.
    """
    declared = set(_declared())
    local = {path.stem for path in (COUNSEL / "app").rglob("*.py")}
    local |= {
        path.parent.name
        for path in (COUNSEL / "app").rglob("__init__.py")
        if path.parent != COUNSEL / "app"
    }
    local |= {"app"}
    imports: set[str] = set()
    for path in (COUNSEL / "app").rglob("*.py"):
        imports |= set(
            re.findall(
                r"^\s*(?:import|from)\s+([A-Za-z_][A-Za-z0-9_]*)",
                path.read_text(encoding="utf-8"),
                re.M,
            )
        )
    third_party = {
        module for module in imports if module not in sys.stdlib_module_names and module not in local
    }
    assert third_party == declared, {
        "undeclared_imports": sorted(third_party - declared),
        "unused_declarations": sorted(declared - third_party),
    }
