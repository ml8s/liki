        w.writeheader()
        for rid, event, conds, concl, basis, src in rows:
            row = {"id": rid, "事件": event, "结论": concl, "依据": basis, "经典原文": src}
            for c in ZW_COLS:
                row[c] = conds.get(c, "")
            w.writerow(row)
