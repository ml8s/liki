"""counsel MCP server（正交化断语引擎）。

暴露判断工具，按 domain 分域（bazi/ziwei/liuyao/qimen/naming）：
- bazi：bazi_yongshen / compute_factors / natal_query / period_query
- ziwei：compute_factors / natal_query / period_query（因子快照 + 断语）
- naming：起名（surname/pick/char/compose/check；字库与音韵在本地）
内部调 engine（排盘）取判断所需字段，再在进程内求因子/断语/评估；
无状态、无存储依赖。counsel 是 engine 的补集（判断），排盘/历法在 engine。

Run:
    LIKI_MCP_URL=http://engine-mcp:8081/mcp \
        .venv/bin/python -m uvicorn app.counsel_mcp:app --host 127.0.0.1 --port 8086
"""

import logging
import os
from contextlib import AsyncExitStack, asynccontextmanager

import anyio
from starlette.applications import Starlette
from starlette.middleware import Middleware
from starlette.responses import JSONResponse, Response
from starlette.routing import Route

from app import engine_mcp_client  # noqa: E402
from app.counsel_servers import (  # noqa: E402
    RUNTIME_VERSION,
    create_counsel_mcp,
    create_counsel_root_mcp,
)
from app.http_middleware import AuthMiddleware, BodyLimitMiddleware
from app.metrics import render_metrics  # noqa: E402


def _make_app():
    """Build the standard Starlette application for all Counsel domains.

    Each domain is a complete MCP Streamable HTTP application generated by the
    official MCP SDK. Starlette owns routing and the combined ASGI lifespan.
    The public `/counsel` prefix is stripped by the gateway; this process owns
    only `/mcp` and `/mcp/{domain}`.
    """
    domains = ("bazi", "ziwei", "liuyao", "qimen", "naming")
    root_app = create_counsel_root_mcp().streamable_http_app(
        streamable_http_path="/mcp",
        json_response=True,
        stateless_http=True,
        host="0.0.0.0",
    )
    domain_apps = {
        domain: create_counsel_mcp(domain).streamable_http_app(
            streamable_http_path=f"/mcp/{domain}",
            json_response=True,
            stateless_http=True,
            host="0.0.0.0",
        )
        for domain in domains
    }

    async def healthz(_request):
        return JSONResponse({
            "status": "ok",
            "version": RUNTIME_VERSION,
            "domains": list(domains),
        })

    async def readyz(_request):
        try:
            timeout = float(os.environ.get("LIKI_READYZ_TIMEOUT_SECONDS", "1"))

            def discover_engine():
                return engine_mcp_client.server_info(
                    retries=0, timeout=timeout
                )

            await anyio.to_thread.run_sync(discover_engine)
        except (OSError, TimeoutError, ValueError, engine_mcp_client.MCPError):
            return JSONResponse(
                {
                    "status": "unavailable",
                    "reason": "engine_dependency_unreachable",
                },
                status_code=503,
            )
        return JSONResponse({
            "status": "ready",
            "version": RUNTIME_VERSION,
        })

    async def metrics(_request):
        return Response(
            render_metrics(),
            media_type="text/plain; version=0.0.4; charset=utf-8",
        )

    @asynccontextmanager
    async def lifespan(app: Starlette):
        """Fail fast on misconfiguration; run each domain app's lifespan once."""
        if not os.environ.get("LIKI_MCP_URL", "").strip():
            raise RuntimeError(
                "LIKI_MCP_URL is required "
                "(engine-mcp endpoint, e.g. http://engine-mcp:8081/mcp)"
            )
        if not os.environ.get("LIKI_MCP_TOKEN", ""):
            logging.getLogger(__name__).warning(
                "counsel-mcp: LIKI_MCP_TOKEN is empty; set a token unless a "
                "trusted edge already gates access"
            )
        async with AsyncExitStack() as stack:
            await stack.enter_async_context(root_app.router.lifespan_context(root_app))
            for domain in domains:
                domain_app = domain_apps[domain]
                await stack.enter_async_context(
                    domain_app.router.lifespan_context(domain_app)
                )
            yield

    routes = [
        Route("/healthz", healthz, methods=["GET"]),
        Route("/readyz", readyz, methods=["GET"]),
        Route("/metrics", metrics, methods=["GET"]),
        *(
            Route(f"/mcp/{domain}", endpoint=domain_apps[domain])
            for domain in domains
        ),
        Route("/mcp", endpoint=root_app),
    ]
    return Starlette(
        routes=routes,
        lifespan=lifespan,
        middleware=[
            Middleware(
                AuthMiddleware,
                token=os.environ.get("LIKI_MCP_TOKEN", ""),
            ),
            Middleware(
                BodyLimitMiddleware,
                max_body_bytes=int(os.environ.get("LIKI_MCP_MAX_BODY_BYTES", str(1024 * 1024))),
            ),
        ],
    )

app = _make_app()

if __name__ == "__main__":
    import uvicorn

    uvicorn.run(app, host="127.0.0.1", port=8086)
